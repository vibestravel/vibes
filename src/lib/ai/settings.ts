export async function getSettings(which: "draft" | "published" = "published"): Promise<AiSettings> {
  const [row] = await db.select().from(aiSettings).where(eq(aiSettings.id, which));
  if (row) return row;
  return { id: which, ...DEFAULT_SETTINGS, updatedAt: new Date(), publishedAt: null };
}

